-- ============================================================================
--  BidTagglia: bid rankings.
--  Run this in Supabase -> SQL Editor. Safe to re-run.
--
--  Until it runs, the Request ranking button and the Ranking tab say so and do
--  nothing; the rest of the app is unaffected.
--
--  One row per person asked to rank one bid. "Request ranking" on a bid adds a
--  row for each person picked (the requester included); that person scores it
--  on the Ranking tab, which fills in `scores`, `score` and `submitted_at`. The
--  number shown on the bid is the average `score` of the rows submitted so far.
--
--  `scores` holds the 1-4 answer per criterion, keyed as in RANKING_CRITERIA
--  in rankings.js. `score` is the weighted total out of 100 worked out when it
--  was submitted, stored rather than recomputed so that re-weighting the
--  criteria later doesn't quietly rewrite rankings people already gave.
--
--  opportunity_id is TEXT, like the pricing and team tables, and is cleared
--  out by the app when a bid is deleted.
-- ============================================================================

create table if not exists public.bid_rankings (
  id             bigint generated by default as identity primary key,
  opportunity_id text not null,
  identity       text not null,          -- app_members.identity of the ranker
  name           text,                   -- their name when they were asked
  requested_by   text,                   -- app_members.identity of the requester
  requested_at   timestamptz not null default now(),
  scores         jsonb,
  score          numeric check (score is null or (score >= 0 and score <= 100)),
  submitted_at   timestamptz,
  -- Asking someone twice about the same bid is the same request, not two.
  unique (opportunity_id, identity)
);

create index if not exists bid_rankings_identity_idx
  on public.bid_rankings(identity);

alter table public.bid_rankings enable row level security;
drop policy if exists "anon full access rankings" on public.bid_rankings;
create policy "anon full access rankings" on public.bid_rankings
  for all to anon using (true) with check (true);

-- Sanity check — should come back true.
select exists (select 1 from information_schema.tables
                where table_name = 'bid_rankings') as rankings_ready;
